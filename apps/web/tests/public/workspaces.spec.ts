import { test, expect } from "@playwright/test";

test("built application through Caddy keeps visitor data isolated and restores the full proposal workflow", async ({browser}) => {
  const alice = await browser.newContext();
  const bob = await browser.newContext();
  const page = await alice.newPage();
  const other = await bob.newPage();
  await page.goto("/");
  await expect(page.getByRole("complementary", {name: "Temporary demo workspace"})).toBeVisible();
  const home = await alice.request.get("/");
  expect(home.headers()["content-security-policy"]).toContain("frame-ancestors 'none'");
  expect(home.headers()["x-content-type-options"]).toBe("nosniff");
  const imported = await alice.request.post("/api/documents", {data: {title: "Fictional private-to-this-demo source", content: "This fictional record belongs only to this visitor."}});
  expect(imported.status()).toBe(201);
  const source = await imported.json();
  await page.getByRole("link", {name: "Simulation", exact: true}).click();
  await page.getByRole("checkbox").check();
  await page.getByRole("button", {name: "Start rehearsal", exact: true}).click();
  await page.getByRole("button", {name: "Choose: Escalate to operations lead", exact: true}).click();
  await expect(page.getByRole("heading", {name: "The procedure has no matching path."})).toBeVisible();
  const parent = new URL(page.url()).pathname.split("/").at(-1)!;
  await page.getByText("Propose a rule change", {exact: true}).click();
  const form = page.locator(".proposal-section");
  await form.getByLabel("Reason for the change").fill("Fictional public demo capacity experiment");
  await form.getByRole("button", {name: "Add choice for current facts", exact: true}).click();
  await form.getByLabel("Action label", {exact: true}).last().fill("Pause admission and contact venue manager");
  await form.getByRole("button", {name: "Save unapproved proposal", exact: true}).click();
  await form.getByRole("checkbox").check();
  await form.getByRole("button", {name: "Rehearse proposal", exact: true}).click();
  await page.getByRole("button", {name: "Choose: Pause admission and contact venue manager", exact: true}).click();
  await page.getByRole("button", {name: "Compare with parent", exact: true}).click();
  await expect(page.getByRole("region", {name: "Run comparison"})).toContainText("Same scenario, different policy");
  const alternate = new URL(page.url()).pathname.split("/").at(-1)!;
  await page.reload();
  await page.getByRole("button", {name: "Verify replay", exact: true}).click();
  await expect(page.getByText(/Replay verified against pinned inputs/)).toBeVisible();
  await other.goto("/");
  expect((await bob.request.get(`/api/documents/${source.id}`)).status()).toBe(404);
  expect((await bob.request.get(`/api/sessions/${parent}/report`)).status()).toBe(404);
  await other.goto(`/simulation/${alternate}`);
  await expect(other.getByRole("heading", {name: "Run unavailable"})).toBeVisible();
  await page.getByRole("link", {name: "Session report", exact: true}).click();
  await expect(page.getByRole("heading", {name: "Proposed rule changes · unapproved"})).toBeVisible();
  expect((await alice.request.get(`/api/sessions/${alternate}/report`)).headers()["cache-control"]).toBe("no-store");
  await page.setViewportSize({width: 390, height: 844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path: test.info().outputPath("public-report-mobile.png"), fullPage: true});
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", {name: "Start fresh workspace", exact: true}).click();
  await expect(page).toHaveURL("http://127.0.0.1:4174/");
  expect((await alice.request.get(`/api/sessions/${parent}`)).status()).toBe(404);
  await alice.close();
  await bob.close();
});
