import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { comparisonSchema, reportSchema } from "../../src/lib/api";

test("an imported procedure can be modeled, given its own scenario, rehearsed and found again", async ({page})=>{
  await page.goto("/import");
  await page.getByLabel("Document title").fill("Fictional authored vendor procedure");
  await page.getByLabel("Procedure text").fill("Vendor delays of at least 30 minutes must be escalated to the operations lead.");
  await page.getByRole("button",{name:"Import document",exact:true}).click();
  await page.getByRole("button",{name:"Model decision rules",exact:true}).click();
  await page.getByRole("button",{name:"Add decision before completion",exact:true}).click();
  await page.getByLabel("Decision question").fill("Is vendor escalation required?");
  const rule=page.locator(".revision-node");
  await rule.getByLabel("Action label",{exact:true}).fill("Escalate vendor delay");
  await rule.getByLabel("Fact name",{exact:true}).fill("vendor_delay_minutes");
  await rule.getByLabel("Comparison",{exact:true}).selectOption("gte");
  await rule.getByRole("textbox",{name:"Comparison value",exact:true}).fill("30");
  await rule.getByRole("checkbox").check();
  await page.getByRole("button",{name:"Save draft revision",exact:true}).click();
  await expect(page.getByText(/vendor_delay_minutes.*at least.*30/)).toBeVisible();
  await page.getByRole("link",{name:"Version history",exact:true}).click();
  await expect(page.locator(".version-history>li")).toHaveCount(2);
  await page.locator(".version-history>li").last().getByRole("link",{name:"Inspect version",exact:true}).click();
  await page.getByRole("link",{name:"Create scenario",exact:true}).click();
  await page.getByLabel("Scenario title",{exact:true}).fill("Fictional authored late delivery");
  await page.getByLabel("Description",{exact:true}).fill("A recorded experiment for the imported procedure.");
  await page.locator(".fact-row").first().getByLabel("Fact value",{exact:true}).fill("0");
  await page.getByRole("button",{name:"Add scheduled change",exact:true}).click();
  const inject=page.locator(".inject-editor");
  await inject.getByLabel("Before step",{exact:true}).selectOption({label:"Is vendor escalation required?"});
  await inject.getByLabel("Fact name",{exact:true}).fill("vendor_delay_minutes");
  await inject.getByLabel("Fact value",{exact:true}).fill("45");
  await page.getByRole("checkbox").check();
  await page.getByRole("button",{name:"Save scenario",exact:true}).click();
  await expect(page).toHaveURL(/\/simulation\?scenario=/);
  await expect(page.getByRole("heading",{name:"Fictional authored late delivery",exact:true})).toBeVisible();
  await page.getByRole("checkbox").check();
  await page.getByRole("button",{name:"Start rehearsal",exact:true}).click();
  await page.getByRole("button",{name:"Choose: Escalate vendor delay",exact:true}).click();
  await expect(page.getByText(/The modeled workflow reached its end/)).toBeVisible();
  const runUrl=page.url();
  await page.getByRole("link",{name:"Library",exact:true}).click();
  await page.getByRole("button",{name:/^Sessions/}).click();
  const card=page.locator(".library-card").filter({hasText:"Fictional authored late delivery"}).first();
  await card.getByRole("link",{name:"Resume run",exact:true}).click();
  await expect(page).toHaveURL(runUrl);
  await page.getByRole("link",{name:"Session report",exact:true}).click();
  const [download]=await Promise.all([page.waitForEvent("download"),page.getByRole("link",{name:"Download report JSON"}).click()]);
  const file=test.info().outputPath("authored-report.json");await download.saveAs(file);
  const report=reportSchema.parse(JSON.parse(await readFile(file,"utf8")));
  expect(report.status).toBe("completed");expect(report.replay_input.scenario.seed).toBe(0);
  expect(report.evidence[0].text).toContain("30 minutes");
  expect(report.final_facts.vendor_delay_minutes).toBe(45);
  await page.setViewportSize({width:390,height:844});
  await page.goto(`/library?tab=sessions&q=${new URL(runUrl).pathname.split("/").at(-1)}`);
  await expect(page.locator(".library-card")).toHaveCount(1);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:test.info().outputPath("library-mobile.png"),fullPage:true});
});

test("Replay Lab forks a real checkpoint and exports an evidence-complete comparison", async ({page})=>{
  await page.goto("/simulation?scenario=night-market");await page.getByRole("checkbox").check();
  await page.getByRole("button",{name:"Start rehearsal",exact:true}).click();
  await page.getByRole("button",{name:"Choose: Escalate to operations lead",exact:true}).click();
  await expect(page.getByRole("heading",{name:"The procedure has no matching path."})).toBeVisible();
  const parentUrl=page.url();
  await page.getByRole("link",{name:"Replay Lab",exact:true}).click();
  await page.getByLabel("Jump to an event",{exact:true}).selectOption("2");
  await page.getByRole("button",{name:"Fork before this decision",exact:true}).focus();
  await page.keyboard.press("Enter");
  await expect(page).not.toHaveURL(parentUrl);
  await page.getByRole("button",{name:"Choose as deviation: Continue routine intake",exact:true}).click();
  await page.getByRole("link",{name:"Replay Lab",exact:true}).click();
  await page.getByRole("button",{name:"Verify replay",exact:true}).click();
  await expect(page.getByText("Pinned inputs reproduce the stored history.")).toBeVisible();
  await expect(page.getByRole("row",{name:/Deviations\s+0\s+1/})).toBeVisible();
  await page.screenshot({path:test.info().outputPath("replay-lab.png"),fullPage:true});
  await page.getByRole("link",{name:"Open printable comparison & export ↗"}).click();
  await expect(page.getByRole("heading",{name:"Two paths, inspected."})).toBeVisible();
  const [download]=await Promise.all([page.waitForEvent("download"),page.getByRole("link",{name:"Download comparison JSON",exact:true}).click()]);
  const file=test.info().outputPath("comparison-report.json");await download.saveAs(file);
  const comparison=comparisonSchema.parse(JSON.parse(await readFile(file,"utf8")));
  expect(comparison.left.deviation_count).toBe(0);expect(comparison.right.deviation_count).toBe(1);
  expect(comparison.left.evidence.length).toBeGreaterThan(0);
  expect(comparison.right.logical_events.at(-1)?.state_hash).toBe(comparison.right.last_state_hash);
  await page.screenshot({path:test.info().outputPath("comparison-report.png"),fullPage:true});
  await page.emulateMedia({media:"print"});await expect(page.locator(".app-header")).toBeHidden();
  await expect(page.getByRole("heading",{name:"Two paths, inspected."})).toBeVisible();
});

test("a real text PDF imports with page provenance and can be recovered from the library",async({page})=>{
  const {execFileSync}=await import("node:child_process");
  const {resolve}=await import("node:path");
  const bytes=execFileSync(resolve("../../services/api/.venv/bin/python"),["-c","from tests.helpers.pdf import make_pdf; import sys; sys.stdout.buffer.write(make_pdf(['Fictional vendor operations.',None,'Escalate delivery delays of at least 30 minutes.']))"],{cwd:resolve("../../services/api")});
  await page.goto("/import");
  await page.getByRole("button",{name:"Upload PDF",exact:true}).click();
  await page.getByLabel("Document title",{exact:true}).fill("Fictional PDF vendor source");
  await page.getByLabel("Text-based PDF",{exact:true}).setInputFiles({name:"fictional-vendor.pdf",mimeType:"application/pdf",buffer:bytes});
  await page.getByRole("button",{name:"Import document",exact:true}).click();
  await expect(page.getByText("Extracted PDF text · 3 pages",{exact:true})).toBeVisible();
  await expect(page.getByText(/No extractable text on page\(s\) 2/)).toBeVisible();
  await expect(page.getByText("PDF page 3",{exact:true})).toBeVisible();
  await page.getByRole("link",{name:"Open saved source ↗",exact:true}).click();
  await page.reload();
  await expect(page.getByRole("heading",{name:"Fictional PDF vendor source",exact:true})).toBeVisible();
  await expect(page.getByText("PDF page 3",{exact:true})).toBeVisible();
  await page.screenshot({path:test.info().outputPath("pdf-source.png"),fullPage:true});
  await page.getByRole("link",{name:"Library",exact:true}).click();
  await page.getByRole("link",{name:"Fictional PDF vendor source",exact:true}).first().click();
  await expect(page.getByText(/Original PDF SHA-256:/)).toBeVisible();
});

test("action steps can be authored and removed in new revisions without editing the original",async({page,request})=>{
  const source=await(await request.post("/api/documents",{data:{title:"Fictional action procedure",content:"Notify the operations lead before completing intake."}})).json();
  const draft=await(await request.post(`/api/documents/${source.id}/draft`,{data:{title:source.title}})).json();
  await page.goto(`/review/${draft.id}?edit=1`);
  await page.getByRole("button",{name:"Add action before completion",exact:true}).click();
  await page.getByLabel("Action step label",{exact:true}).fill("Notify operations lead");
  const action=page.getByRole("group",{name:"Action evidence: Notify operations lead"});
  await action.getByRole("checkbox").check();
  await page.getByRole("button",{name:"Save draft revision",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Action: Notify operations lead",exact:true})).toBeVisible();
  expect((await(await request.get(`/api/playbooks/${draft.id}`)).json()).graph.nodes).toHaveLength(2);
  await page.getByText("Create a new revision",{exact:true}).click();
  const editor=page.getByRole("group",{name:"Action evidence: Notify operations lead"});
  await editor.getByText("Remove this step from the draft revision",{exact:true}).click();
  await editor.getByRole("button",{name:"Remove step: Notify operations lead",exact:true}).click();
  await page.getByRole("button",{name:"Save draft revision",exact:true}).click();
  await expect(page.getByText("This source has no modeled rules yet.",{exact:false})).toBeVisible();
  await expect(page.getByRole("button",{name:"Approve reviewed version",exact:true})).toBeDisabled();
});
